/* single entry point into a topic drill (deep link ?practice=<topicKey>, and the guided courses' "to the real questions") */
function startTopicPractice(topic){
  if(!TOPICS.some(([k])=>k===topic) || topicPool(topic).length===0) return false;
  S.mode="topic"; S.topic=topic;
  const r=document.querySelector('input[name=mode][value="topic"]'); if(r) r.checked=true;
  initStart(); startSession();
  return true;
}
/* deep links: index.html?practice=<topicKey>  |  index.html?learn=<chapterId> */
function autoStartFromURL(){
  let t, c;
  try{ const u=new URLSearchParams(location.search); t=u.get("practice"); c=u.get("learn"); }catch(e){ return; }
  if(t) startTopicPractice(t);
  else if(c && openLearnAt) openLearnAt(c);
}

