/* ---------- rubric (shared by the solution panel and the simulation results) ---------- */
function rubricHtml(q){
  if(!Array.isArray(q.rubric) || !q.rubric.length) return "";
  const t = ticksOf(q), max = maxOf(q), got = rubricScore(q);
  const note = provNote(q.rubricSource);
  return `<div class="rubric" data-qid="${escapeHtml(q.id)}"><h4 class="sec-h">מחוון — סמנו את מה שהשגתם</h4>`+
    q.rubric.map((r,i)=>
      `<label class="rub-item"><input type="checkbox" data-k="${i}"${t[i]?" checked":""}>`+
      `<span class="rub-txt">${iso(r.html || escapeHtml(r.text))}</span><span class="rub-pts">${+r.points||0} נק׳</span></label>`).join("")+
    `<div class="rubric-total">ציון עצמי: <b><bdi dir="ltr">${got} / ${max}</bdi></b></div>`+
    (note?`<div class="ai-note">${note}</div>`:"")+`</div>`;
}
function bindRubric(root, q, onChange){
  const box = root.querySelector(".rubric");
  if(!box) return;
  box.querySelectorAll('input[type=checkbox]').forEach(c=>{
    c.onchange=()=>{
      P.ticks[q.id] = [...box.querySelectorAll('input[type=checkbox]')].map(x=>x.checked);
      const got=rubricScore(q), max=maxOf(q);
      box.querySelector(".rubric-total").innerHTML = `ציון עצמי: <b><bdi dir="ltr">${got} / ${max}</bdi></b>`;
      record(q, { selfScore: got, max });
      renderTopStats();
      if(onChange) onChange();
    };
  });
}

