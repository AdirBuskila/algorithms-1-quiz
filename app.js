function escapeHtml(s){ return String(s).replace(/[&<>"]/g,m=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;"}[m])); }
function textToHtml(s){ return escapeHtml(s).replace(/\n/g,"<br>"); }
function hasHebrew(s){ return /[֐-׿]/.test(String(s)); }
function optById(q,id){ return (q.options||[]).find(o=>o.id===id); }
function acceptedIdsOf(q){ return (Array.isArray(q.acceptedIds) && q.acceptedIds.length) ? q.acceptedIds : [q.correctId]; }
function isAccepted(q,id){ return id!=null && acceptedIdsOf(q).includes(id); }
function dedupePool(arr){
  const seen=new Set(), out=[];
  for(const q of arr){ const k=q.dedupKey||q.id; if(seen.has(k)) continue; seen.add(k); out.push(q); }
  return out;
}
function qNum(q){ if(Number.isInteger(q.num)) return q.num; const m=String(q.id).match(/-Q(\d+)/); return m?parseInt(m[1],10):0; }
function examLabelOf(q){ return q.examLabel || q.examCode || ""; }
/* Exam-picker order: sample papers first, then real exams oldest -> newest. */
function examOrder(code){
  const c=String(code);
  if(/^SAMP/.test(c)) return [0,0,c];
  const m=c.match(/^(\d{2})/);
  return [1, m?2000+parseInt(m[1],10):9999, c];
}
function byExamOrder(a,b){ const x=examOrder(a), y=examOrder(b); return (x[0]-y[0]) || (x[1]-y[1]) || String(x[2]).localeCompare(String(y[2])); }
function sortQs(arr){
  return arr.slice().sort((a,b)=> byExamOrder(a.examCode,b.examCode) || qNum(a)-qNum(b) || String(a.partKey||"").localeCompare(String(b.partKey||"")));
}
function examQuestions(code){ return sortQs(QS.filter(q=>q.examCode===code)); }
function maxOf(q){
  if(Array.isArray(q.rubric) && q.rubric.length) return q.rubric.reduce((s,r)=>s+(+r.points||0),0);
  return +q.pointsTotal || 0;
}
function provNote(src){ return (!src || src==="official") ? "" : (src==="ai-draft" ? AI_DRAFT_NOTE : AI_NOTE); }

/* ---------- rendering pieces (all *Html fields are trusted build output) ---------- */
function contextHtml(ctx){
  if(!ctx) return "";
  let h = `<div class="ctx ctx-${escapeHtml(ctx.kind||"text")}">`;
  if(ctx.title) h += `<div class="ctx-title">${ctx.titleHtml || escapeHtml(ctx.title)}</div>`;
  if(ctx.image) h += `<figure class="ctx-fig"><img class="q-img ctx-img" src="${escapeHtml(ctx.image)}" alt="${escapeHtml(ctx.caption||ctx.title||"")}" loading="lazy">`+
                     (ctx.caption?`<figcaption>${ctx.captionHtml || escapeHtml(ctx.caption)}</figcaption>`:"")+`</figure>`;
  if(ctx.text) h += `<div class="ctx-text">${iso(ctx.textHtml || escapeHtml(ctx.text))}</div>`;
  if(ctx.code) h += `<pre class="code-ctx" dir="ltr"><code dir="ltr">${ctx.codeHtml || escapeHtml(ctx.code)}</code></pre>`;
  h += `</div>`;
  return h;
}
function extrasHtml(q){
  return q.image ? `<figure class="q-fig"><img class="q-img" src="${escapeHtml(q.image)}" alt="" loading="lazy"></figure>` : "";
}
/* bidi: Latin labels / formulas inside Hebrew are isolated at render time (Bidi lives in normalize.js, loaded first) */
function iso(h){ return window.Bidi ? window.Bidi.render(h) : h; }
function questionHtml(q){ return iso(q.questionHtml || escapeHtml(q.question||"")); }
/* feedback.js: "report a mistake" mailto link for a question (renders nothing if the helper is absent) */
function reportData(q){ return {id:q.id, exam:examLabelOf(q), html:q.questionHtml || escapeHtml(q.question||"")}; }
function reportRowHtml(q){ return window.Feedback ? window.Feedback.reportRow(reportData(q)) : ""; }
function optionHtml(o){
  if(!o) return "";
  const type = o.type || "text";
  if(type==="image") return `<img class="opt-img" src="${escapeHtml(o.value)}" alt="" loading="lazy">`;
  const body = type==="math" ? (o.html || escapeHtml(o.value)) : iso(o.html || escapeHtml(o.value));
  if(type==="math") return body;
  if(!hasHebrew(o.value)) return `<span class="opt-ltr" dir="ltr">${body}</span>`;
  return body;
}

