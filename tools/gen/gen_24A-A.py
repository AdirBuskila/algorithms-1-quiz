def clean(src):
    out = []
    for ln in src.strip("\n").split("\n"):
        ln = ln.split("//")[0].rstrip()
        if ln.strip():
            out.append(ln)
    return out


def swap1(lines, old, new):
    idx = [i for i, ln in enumerate(lines) if ln.strip() == old.strip()]
    assert len(idx) == 1, old
    out = list(lines)
    out[idx[0]] = out[idx[0]].replace(old.strip(), new.strip())
    return out, idx[0]


