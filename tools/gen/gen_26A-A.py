CODE_4B = r"""#include <stdio.h>

int findKthMissing(int A[], int size, int k) {
    int low = 0;
    int high = size - 1;

    //We perform a binary search on the sorted array.
    //
    //Key observation:
    //At index i, the number of missing positive integers
    //before A[i] is given by:
    //    A[i] - (i + 1)
    //
    //This is because, in a perfect sequence without missing numbers,
    //the value at index i should be exactly (i + 1).

    while (low <= high) {
        int mid = low + (high - low) / 2;

        // Number of missing positive integers up to index mid
        int missing = A[mid] - (mid + 1);

        //If the number of missing values is smaller than k,
        //then the k-th missing number must be located
        //to the right of mid.

        if (missing < k) {
            low = mid + 1;
        }
        //Otherwise, there are already at least k missing numbers
        //up to index mid, so we continue searching on the left side.
        else {
            high = mid - 1;
        }
    }

    //After the loop terminates:
    //'low' points to the first index where the number of
    //missing values is greater than or equal to k.
    //
    //The k-th missing positive integer is therefore:
    //    k + low

    return low + k;
}

int main() {
    int A[] = { 3, 5, 9, 10, 11, 12 };
    int k = 3;
    int size = sizeof(A) / sizeof(A[0]);

    printf("The %d-th missing number is: %d\n", k, findKthMissing(A, size, k));
    return 0;
}"""

