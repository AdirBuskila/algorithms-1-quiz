# the trap: dividing with rounding down (7 // 2 = 3, 7 // 3 = 2) makes 7 look like 2 operations
C_floor = [None, 0] + [None] * (K - 1)
for i in range(2, K + 1):
    C_floor[i] = 1 + min(C_floor[i - 1], C_floor[i // 2], C_floor[i // 3] if i >= 3 else C_floor[i - 1])
assert C_floor[7] == 2 != C[7]

