"""G04 · תת-מבנה אופטימלי והוכחה שלמה — video script (build: tools/video/vid.py G04).

Source: courses/greedy_proofs/C04.js (goal: complete the proof with optimal substructure, and show another optimal
solution when the optimum is not unique). Exam anchors: SAMP-1-Q4a (is the optimum unique? the circles) and SAMP-1-Q4d
(prove optimal substructure), open questions no guided level uses.
Avoided on purpose: the C04 quiz/lesson data (the 11-interval input and its sub-problem, points 10,15,22,31,34,60 with
length 10, budget 8 with 3,3,5) and every other level's quiz. The worked sub-problem uses a new 7-interval input.
Every optimum below comes from brute force (W.iv_all_optima, CHK.iv_opt).
"""
from vid import P, Scene, Video, show, hide, BANK
import stage as st
import w_greedy_proofs as W

CHK = W.CHK
EF = lambda x: (x[1], x[0])

# ---------------------------------------------------------------- worked: the sub-problem after the greedy choice
IV = [(1, 3), (2, 6), (4, 7), (5, 9), (8, 10), (9, 12), (11, 13)]
g = W.iv_greedy_run(IV, EF)[0][0]
assert g == 0
SUB = [i for i in range(len(IV)) if i != g and not W.conflict(IV[i], IV[g])]
assert SUB == [2, 3, 4, 5, 6] and all(IV[i][0] > IV[g][1] for i in SUB)     # the rest = everything starting after 3
SUBIV = [IV[i] for i in SUB]
assert CHK.iv_opt(SUBIV) == 3 and CHK.iv_opt(IV) == 4 == 1 + CHK.iv_opt(SUBIV)
BEST_SUB = (2, 4, 6)                                   # [4,7], [8,10], [11,13]
assert BEST_SUB in [tuple(SUB[i] for i in t) for t in W.iv_all_optima(SUBIV)]

# ---------------------------------------------------------------- exam SAMP-1-Q4a / Q4d: the circles
QA, QD = BANK["SAMP-1-Q4a"], BANK["SAMP-1-Q4d"]
assert QA["contextId"] == QD["contextId"] == "SAMP-1-c4"
CIRC = [(-4.5, 2), (0, 2), (0, 3), (5, 4), (6, 2), (7, 5), (8, 3)]
CV = [(c - r, c + r) for c, r in CIRC]
OPTS = W.iv_all_optima(CV)
assert sorted(OPTS) == [(0, 1, 4), (0, 1, 6)]        # exactly two optimal sets: {c1,c2,c5} and {c1,c2,c7}
assert W.iv_greedy_run(CV, EF)[0] == (0, [2])         # greedy picks c1 and deletes only c3
assert W.conflict(CV[0], CV[2])                       # c1 and c3 intersect (the trap of the official answer)
CSUB = [1, 3, 4, 5, 6]
assert [i for i in range(7) if i != 0 and not W.conflict(CV[i], CV[0])] == CSUB
assert CHK.iv_opt([CV[i] for i in CSUB]) == 2 and CHK.iv_opt(CV) == 3
NAMES = [f"c{i + 1}" for i in range(7)]
SC = {i: f"סִי {w}" for i, w in enumerate(["אחת", "שתיים", "שלוש", "ארבע", "חמש", "שש", "שבע"])}

T1 = W.timeline("t1", IV, 0, 14, w=920, row=52, guides=[(3, "f(g) = 3")])
TC = W.timeline("tc", CV, -7, 12, names=NAMES, w=980, row=50, ticks=range(-6, 13, 2))

